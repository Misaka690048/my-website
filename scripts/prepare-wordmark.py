"""Freeze the existing EB Garamond 600 wordmark into inline SVG outlines.

Offline maintenance only: python3 scripts/prepare-wordmark.py
Uses HarfBuzz shaping/drawing, preserving kerning and the existing -.015em tracking.
The resulting mark has no font/network dependency in the browser.
"""
import ctypes as c
import ctypes.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
hb = c.CDLL(ctypes.util.find_library('harfbuzz'))
ptr = c.c_void_p


def call(name, args, result):
    fn = getattr(hb, name)
    fn.argtypes, fn.restype = args, result
    return fn


class Variation(c.Structure):
    _fields_ = [('tag', c.c_uint), ('value', c.c_float)]


class Info(c.Structure):
    _fields_ = [(name, c.c_uint) for name in ('glyph', 'mask', 'cluster', 'var1', 'var2')]


class Position(c.Structure):
    _fields_ = [(name, c.c_int) for name in ('advance_x', 'advance_y', 'offset_x', 'offset_y', 'var')]


class Extents(c.Structure):
    _fields_ = [(name, c.c_int) for name in ('ascender', 'descender', 'line_gap')] + [('reserved', c.c_int * 9)]


blob = call('hb_blob_create_from_file_or_fail', [c.c_char_p], ptr)(str(ROOT.parent / 'EBGaramond[wght].ttf').encode())
if not blob:
    raise SystemExit('Missing source EBGaramond[wght].ttf')
face = call('hb_face_create', [ptr, c.c_uint], ptr)(blob, 0)
font = call('hb_font_create', [ptr], ptr)(face)
call('hb_ot_font_set_funcs', [ptr], None)(font)
call('hb_font_set_scale', [ptr, c.c_int, c.c_int], None)(font, 1000, 1000)
variation = Variation(int.from_bytes(b'wght', 'big'), 600)
call('hb_font_set_variations', [ptr, c.POINTER(Variation), c.c_uint], None)(font, c.byref(variation), 1)
buffer = call('hb_buffer_create', [], ptr)()
text = b'imisslog.'
call('hb_buffer_add_utf8', [ptr, c.c_char_p, c.c_int, c.c_uint, c.c_int], None)(buffer, text, len(text), 0, len(text))
call('hb_buffer_guess_segment_properties', [ptr], None)(buffer)
call('hb_shape', [ptr, ptr, ptr, c.c_uint], None)(font, buffer, None, 0)
count = c.c_uint()
infos = call('hb_buffer_get_glyph_infos', [ptr, c.POINTER(c.c_uint)], c.POINTER(Info))(buffer, c.byref(count))
positions = call('hb_buffer_get_glyph_positions', [ptr, c.POINTER(c.c_uint)], c.POINTER(Position))(buffer, c.byref(count))
assert count.value == len(text) and all(infos[i].glyph for i in range(count.value))

draw = call('hb_draw_funcs_create', [], ptr)()
commands, callbacks = [], []
origin_x = origin_y = 0


def install(name, command, coordinates):
    signature = c.CFUNCTYPE(None, ptr, ptr, ptr, *([c.c_float] * coordinates), ptr)

    def emit(_funcs, _data, _state, *values):
        points = values[:-1]
        coords = [value + origin_x if i % 2 == 0 else -value - origin_y
                  for i, value in enumerate(points)]
        commands.append(command + ' '.join(f'{value:.2f}'.rstrip('0').rstrip('.') if value else '0' for value in coords))

    callback = signature(emit)
    callbacks.append(callback)
    call(f'hb_draw_funcs_set_{name}_func', [ptr, signature, ptr, ptr], None)(draw, callback, None, None)


for name, command, coordinates in [('move_to', 'M', 2), ('line_to', 'L', 2),
                                   ('quadratic_to', 'Q', 4), ('cubic_to', 'C', 6),
                                   ('close_path', 'Z', 0)]:
    install(name, command, coordinates)
pen = 0
for i in range(count.value):
    origin_x, origin_y = pen + positions[i].offset_x, positions[i].offset_y
    call('hb_font_draw_glyph', [ptr, c.c_uint, ptr, ptr], None)(font, infos[i].glyph, draw, None)
    pen += positions[i].advance_x - 15  # Existing CSS letter-spacing: -.015em.

metrics = Extents()
assert call('hb_font_get_h_extents', [ptr, c.POINTER(Extents)], c.c_int)(font, c.byref(metrics))
baseline = (1000 + metrics.ascender + metrics.descender) / 2
svg = f'''<!-- EB Garamond 600; source copyright/license: /fonts/EB-Garamond-OFL.txt.
Generated by scripts/prepare-wordmark.py. Retains the original wordmark's 1em line box. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 {-baseline:g} {pen:g} 1000" width="{pen / 1000:g}em" height="1em" fill="currentColor" aria-hidden="true" focusable="false">
  <path d="{''.join(commands)}" />
</svg>
'''
target = ROOT / 'src/assets/branding/wordmark.svg'
target.write_text(svg)
print(f'{target.name}: {len(svg.encode()):,} bytes; width {pen / 1000:g}em; 8 outlined glyphs; no font dependency')
for name, obj in [('hb_draw_funcs_destroy', draw), ('hb_buffer_destroy', buffer),
                  ('hb_font_destroy', font), ('hb_face_destroy', face), ('hb_blob_destroy', blob)]:
    call(name, [ptr], None)(obj)
